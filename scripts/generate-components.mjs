#!/usr/bin/env node
/**
 * Generates the two lists that have to follow `src/components.ts`:
 *
 * - `src/resolver/components.ts`  registered name -> named export, used by `@antdv-next/mobile/resolver`
 * - `global.d.ts`                 `GlobalComponents` typings for full registration
 *
 * The names are read from the real components (`defineOptions({ name })`), so the lists cannot drift.
 * Run with `pnpm gen:components`; `resolver/tests/resolver.test.ts` fails when the output is stale.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import vue from '@vitejs/plugin-vue'
import { createServer } from 'vite'

const pkg = fileURLToPath(new URL('../packages/antdv-mobile', import.meta.url))

const server = await createServer({
  root: pkg,
  configFile: false,
  logLevel: 'error',
  plugins: [vue()],
  server: { middlewareMode: true, ws: false },
  optimizeDeps: { noDiscovery: true },
})

let components
try {
  components = await server.ssrLoadModule('/src/components.ts')
}
finally {
  await server.close()
}

const entries = Object.entries(components)
  .filter(([, value]) => value && typeof value.name === 'string' && /^Am[A-Z]/.test(value.name) && typeof value !== 'function')
  .map(([exportName, value]) => [value.name, exportName])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))

const names = new Set()
for (const [name] of entries) {
  if (names.has(name)) {
    console.error(`duplicate component name: ${name}`)
    process.exit(1)
  }
  names.add(name)
}

const banner = '// Generated by scripts/generate-components.mjs (pnpm gen:components). Do not edit.'

writeFileSync(
  join(pkg, 'src/resolver/components.ts'),
  `${banner}
const components: Record<string, string> = {
${entries.map(([name, exportName]) => `  ${name}: '${exportName}',`).join('\n')}
}

export default components
`,
)

writeFileSync(
  join(pkg, 'global.d.ts'),
  `${banner}
// Global component types for Volar: add "@antdv-next/mobile/global" to \`compilerOptions.types\`.
declare module 'vue' {
  export interface GlobalComponents {
${entries.map(([name, exportName]) => `    ${name}: typeof import('@antdv-next/mobile')['${exportName}']`).join('\n')}
  }
}

export {}
`,
)

console.log(`generated ${entries.length} components`)
